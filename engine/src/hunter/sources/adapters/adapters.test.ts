// ─── eCFR adapter ────────────────────────────────────────────────────────────

describe('eCFR adapter', () => {
  const URL = 'https://www.ecfr.gov/api/versioner/v1/full/current/title-45.xml?part=164&subpart=E';

  function ecfrFetch(opts: { xmlStatus?: number; fullXmlCalls?: { n: number } } = {}) {
    return vi.fn(async (input: any) => {
      const url = String(input);
      if (url.includes('/titles.json')) return jsonResp(ECFR_TITLES);
      if (url.includes('/versions/title-45.json')) return jsonResp(ECFR_VERSIONS_45_164);
      if (url.includes('/full/') && url.includes('title-45.xml')) {
        if (opts.fullXmlCalls) opts.fullXmlCalls.n++;
        return bytesResp(url, ECFR_XML, 'application/xml', opts.xmlStatus ?? 200);
      }
      throw new Error(`Unexpected fetch: ${url}`);
    }) as unknown as typeof fetch;
  }

  it('fetches the official XML → byte_exact with the correct point-in-time coordinate', async () => {
    const fetchImpl = ecfrFetch();
    const outcome = (await ecfrAdapter.fetch(URL, { fetchImpl })) as AdapterResult;

    expect(outcome.kind).toBe('fetched');
    expect(outcome.provenanceMode).toBe('byte_exact');
    expect(outcome.channel).toBe('official_api');
    // Byte-exact receipt: rawBytesHash == sha256 of the served XML bytes.
    expect(outcome.rawBytesHash).toBe(createHash('sha256').update(Buffer.from(ECFR_XML, 'utf-8')).digest('hex'));
    expect(outcome.contentHash).toBe(sha256Hex(outcome.content));
    expect(outcome.content).toContain('§ 164.502');

    // Coordinate: concrete resolved date (from up_to_date_as_of), title/part/subpart.
    const c = outcome.pointInTimeCoordinate;
    expect(c.authority).toBe('ecfr');
    expect(c.fields.title).toBe(45);
    expect(c.fields.part).toBe('164');
    expect(c.fields.subpart).toBe('E');
    expect(c.fields.date).toBe('2026-07-23'); // resolved from up_to_date_as_of, NOT "current"
    expect(c.fields.partLatestAmendedOn).toBe('2024-05-10'); // max amendment across the part
    expect(c.citation).toContain('45 CFR Part 164 Subpart E @ 2026-07-23');
    // The fetched artifact URL carries the resolved date, not "current".
    expect(outcome.sourceUrl).toContain('/full/2026-07-23/title-45.xml');
  });

  it('CONDITIONAL SKIP: unchanged part last-amended date → not_modified, no full-XML download', async () => {
    const fullXmlCalls = { n: 0 };
    const fetchImpl = ecfrFetch({ fullXmlCalls });
    const outcome = (await ecfrAdapter.fetch(URL, {
      fetchImpl,
      lastContentHash: 'prior-hash',
      lastCoordinate: {
        authority: 'ecfr',
        citation: 'prior',
        fields: { partLatestAmendedOn: '2024-05-10' },
      },
    })) as AdapterNotModified;

    expect(outcome.kind).toBe('not_modified');
    expect(fullXmlCalls.n).toBe(0); // heavy artifact was NOT re-downloaded
  });

  it('re-fetches when the part was amended since the last coordinate', async () => {
    const fullXmlCalls = { n: 0 };
    const fetchImpl = ecfrFetch({ fullXmlCalls });
    const outcome = await ecfrAdapter.fetch(URL, {
      fetchImpl,
      lastContentHash: 'prior-hash',
      lastCoordinate: { authority: 'ecfr', citation: 'prior', fields: { partLatestAmendedOn: '2020-01-01' } },
    });
    expect(outcome.kind).toBe('fetched');
    expect(fullXmlCalls.n).toBe(1);
  });

  it('HARD-FAILS (throws, no fallback) when the official XML fetch fails', async () => {
    const fetchImpl = ecfrFetch({ xmlStatus: 503 });
    await expect(ecfrAdapter.fetch(URL, { fetchImpl })).rejects.toThrow(/HTTP 503|Official fetch failed/i);
  });
});

