// ─── Mock fetch helpers ──────────────────────────────────────────────────────

function jsonResp(body: unknown) {
  return {
    ok: true,
    status: 200,
    url: '',
    headers: { get: () => null },
    json: async () => body,
  };
}

/** A 304 Not Modified response (no body). */
function resp304() {
  return { ok: false, status: 304, url: '', headers: { get: () => null } };
}

/** Read the If-None-Match header a mock fetch received (init.headers is plain). */
function ifNoneMatch(init: any): string | undefined {
  return init?.headers?.['If-None-Match'];
}

function bytesResp(url: string, text: string, contentType = 'application/xml', status = 200) {
  const buf = Buffer.from(text, 'utf-8');
  return {
    ok: status >= 200 && status < 300,
    status,
    url,
    headers: {
      get: (h: string) => {
        const k = h.toLowerCase();
        if (k === 'content-type') return contentType;
        return null;
      },
    },
    arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
    body: { cancel: async () => {} },
  };
}

